/**
 * FrostFlow — PDF Generator & Uploader
 * Generates the PDF report (white-labeled for Studio/Agency) and uploads it. Returns null if storage isn't configured.
 */

import PDFDocument from 'pdfkit';
import { randomBytes } from 'node:crypto';
import type { Score, Issue, GeminiReport } from '@frostflow/types';
import { storageEnabled, uploadBuffer } from '../storage';

const PRIMARY = '#3A6FD8';
const TEXT = '#222222';
const MUTED = '#666666';
const SEVERITY_COLOR: Record<Issue['severity'], string> = {
  critical: '#D6254A', high: '#E0702B', medium: '#B8901A', low: '#0A9E85',
};

function buildPdf(
  url: string,
  score: Score,
  issues: Issue[],
  ai: GeminiReport | null,
  brandName: string
): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: 'A4', bufferPages: true });
    const chunks: Buffer[] = [];
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const h = (text: string, color = PRIMARY, size = 16) => {
      doc.moveDown(0.8).fontSize(size).fillColor(color).text(text).moveDown(0.3);
    };
    const p = (text: string, size = 11, color = TEXT) => {
      doc.fontSize(size).fillColor(color).text(text, { lineGap: 3 });
    };

    doc.fontSize(22).fillColor(PRIMARY).text(brandName, { align: 'right' });
    doc.moveDown(1.5).fontSize(26).fillColor(TEXT).text('Website QA Audit Report');
    doc.fontSize(12).fillColor(MUTED).text(url);
    doc.text(new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }));

    h(`Overall score: ${score.total} / 100  (Grade ${score.grade})`, TEXT, 20);
    const b = score.breakdown;
    p(`Performance ${b.performance}  |  Security ${b.security}  |  Accessibility ${b.accessibility}`, 11, MUTED);
    p(`SEO ${b.seo}  |  Links ${b.links}  |  Mobile ${b.mobile}`, 11, MUTED);

    if (ai) {
      h('Executive summary', PRIMARY, 18);
      p(ai.executiveSummary, 12);
      h('What is working well', TEXT, 14);
      p(ai.whatIsWorkingWell, 11, MUTED);
      if (ai.criticalIssues) {
        h('Critical issues', SEVERITY_COLOR.critical, 14);
        p(ai.criticalIssues);
      }
      h('Fix this week', PRIMARY, 14);
      p(ai.fixThisWeek);
      if (ai.lowerPriorityItems) {
        h('Lower priority', TEXT, 14);
        p(ai.lowerPriorityItems, 11, MUTED);
      }
    }

    const detailed = issues.filter((i) => i.severity === 'critical' || i.severity === 'high').slice(0, 40);
    if (detailed.length > 0) {
      doc.addPage();
      h('High-priority details', PRIMARY, 18);
      for (const issue of detailed) {
        if (doc.y > 700) doc.addPage();
        doc.fontSize(13).fillColor(SEVERITY_COLOR[issue.severity]).text(`[${issue.severity.toUpperCase()}] ${issue.title}`);
        p(`Impact: ${issue.businessImpact}`);
        p(`Technical: ${issue.technicalDetail}`, 9, MUTED);
        if (issue.location) p(`Location: ${issue.location}`, 9, MUTED);
        p(`How to fix: ${issue.fix}`, 10);
        doc.moveDown(1);
      }
    }

    // Footer on every page (requires bufferPages)
    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      doc.fontSize(9).fillColor(MUTED).text(`Generated by ${brandName} — page ${i + 1} of ${range.count}`, 50, doc.page.height - 40, {
        align: 'center',
        lineBreak: false,
      });
    }
    doc.end();
  });
}

export async function generateAndUploadPdf(
  url: string,
  score: Score,
  issues: Issue[],
  ai: GeminiReport | null,
  whiteLabel: { agencyName?: string | null; logoUrl?: string | null }
): Promise<string | null> {
  if (!storageEnabled()) {
    console.warn('[PDF] Uploadthing not configured, skipping PDF.');
    return null;
  }
  try {
    const buffer = await buildPdf(url, score, issues, ai, whiteLabel.agencyName || 'FrostFlow QA');
    return await uploadBuffer(buffer, `report-${Date.now()}-${randomBytes(4).toString('hex')}.pdf`, 'application/pdf');
  } catch (err) {
    console.error('[PDF] generation error:', err);
    return null;
  }
}
